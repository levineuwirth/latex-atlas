"""Generate the hinged cube plates. No dependencies; all output is TikZ.

Five hinges form a tree of six rigid squares. theta=90 closes the cube;
theta=0 lays out its cross-shaped net. The top face has two successive
hinges. The committed TeX is sufficient to build the presentation.
"""
from math import cos, sin, radians, dist
from pathlib import Path


def faces(angle):
    t = radians(angle)
    c, s = cos(t), sin(t)
    result = [[(-1, -1, 0), (1, -1, 0), (1, 1, 0), (-1, 1, 0)]]
    for axis, sign in [(1, 1), (0, 1), (1, -1), (0, -1)]:
        def point(u, v):
            xyz = [0, 0, v*s]
            xyz[axis] = sign*(1+v*c)
            xyz[1-axis] = u
            return tuple(xyz)
        result.append([point(-1, 0), point(1, 0), point(1, 2), point(-1, 2)])
    result.append([(u, 1+2*c+v*cos(2*t), 2*s+v*sin(2*t))
                   for u, v in [(-1, 0), (1, 0), (1, 2), (-1, 2)]])
    return result


def project(p):
    x, y, z = p
    return .9*x-.5*y, .3*x+.55*y+.85*z


def path(points):
    return '--'.join(f'({x:.5f},{y:.5f})' for x, y in points)


def plate(name, angle):
    fs = faces(angle)
    # Camera depth = cross product of the two projection rows.
    def depth(face):
        return sum(-.425*x-.765*y+.645*z for x, y, z in face)/4
    lines = [rf'\newcommand{{\EulerFold{name}}}{{%',
             r'\begin{tikzpicture}[line join=round,line cap=round]',
             r'\path[use as bounding box] (-3.6,-2.1) rectangle (3.6,4.3);']
    for i in sorted(range(6), key=lambda k: depth(fs[k])):
        points = [project(p) for p in fs[i]]
        polygon = path(points)+'--cycle'
        shade = [12, 20, 32, 16, 26, 8][i]
        lines += [rf'\fill[AtlasGold!{shade}!EulerGround] {polygon};',
                  rf'\path[pattern=north east lines,pattern color=AtlasGold,opacity=.12] {polygon};',
                  rf'\draw[EulerStroke,line width=.75pt] {polygon};']
        center = tuple(sum(p[j] for p in points)/4 for j in range(2))
        lines += [rf'\node[text=EulerStroke,font=\scriptsize\scshape] at ({center[0]:.5f},{center[1]:.5f}) {{{["I","II","III","IV","V","VI"][i]}}};']
    lines += [r'\end{tikzpicture}}', '']
    return '\n'.join(lines)


def validate():
    for angle in [0, 22.5, 45, 67.5, 90]:
        fs = faces(angle)
        for f in fs:
            assert all(abs(dist(f[i], f[(i+1)%4])-2)<1e-9 for i in range(4))
            assert abs(dist(f[0], f[2])-8**.5)<1e-9
        assert fs[1][2] == fs[5][1] and fs[1][3] == fs[5][0]
    vertices = {tuple(round(x, 8) for x in p) for f in faces(90) for p in f}
    assert len(vertices) == 8
    # All six flat face interiors occupy distinct unit cells in the net.
    centers = {tuple(round(sum(p[j] for p in f)/4, 8) for j in range(3))
               for f in faces(0)}
    assert len(centers) == 6 and all(p[2] == 0 for p in centers)
    # The three rendered stages must fit the SAME camera box. TikZ would
    # otherwise enlarge its bounds and resize one overlay independently.
    for angle in [90, 55, 0]:
        for f in faces(angle):
            for p in f:
                x, y = project(p)
                assert -3.6 < x < 3.6 and -2.1 < y < 4.3


if __name__ == '__main__':
    validate()
    target = Path(__file__).resolve().parent.parent/'presentations/euler-folds.tex'
    target.write_text('% SPDX-License-Identifier: MIT\n'
                      '% Copyright (c) 2026 the repository contributors\n'
                      '% Generated by tools/euler_geometry.py; edit the generator.\n'
                      '% Six rigid faces, five hinges; all artwork is vector.\n'
                      + '\n'.join(plate(name, angle) for name, angle in
                                  [('Closed', 90), ('Opening', 55), ('Open', 0)]))
    print('Validated six rigid faces and shared hinges; wrote', target.name)
